        private bool _editing;

        private LoadState _loadState = LoadState.Idle;

        /// <summary>When the load/result state was entered (<c>Time.unscaledTime</c>); timeout and
        /// result hold are measured from it.</summary>
        private float _loadStateAt = -1f;

        public int PlayerId => _playerId;

        private RectTransform Rect => _rect != null ? _rect : _rect = (RectTransform)transform;

        /// <summary>
        /// Wires button callbacks. ⚠️ No <c>onClick</c> entries in the prefab: the target player
        /// changes on every <see cref="Bind"/>, so a persistent entry would command the wrong one.
        /// </summary>
        /// <param name="onSelect">Row selected (panel updates the selected player).</param>
        /// <param name="onPopup">Calibration reload failed — the panel shows the reason.</param>
        public void Initialize(Action<int> onSelect, Action<int, string> onPopup)
        {
            _onSelect = onSelect;
            _onPopup = onPopup;

            Wire(selectButton, () => _onSelect?.Invoke(_playerId));
            Wire(ButtonOf(renameButton), BeginNameEdit);
            Wire(nameApplyButton, ApplyNameEdit);
            Wire(nameCancelButton, CancelNameEdit);
            Wire(ButtonOf(kickButton), PressKick);
            // ⚠️ NOT Wire(): onClick fires on pointer-up whatever the duration, so a completed hold
            // would also send the soft reset — the player would be reset twice.
            _resetHold = HoldButton.Attach(ButtonOf(resetButton), PressReset, PressPurge);
            // ⚠️ One step (no confirm): measuring is undoable — a stray press is fixed by measuring
            // again (same reason as AdminPlayerRow).
            Wire(ButtonOf(measureButton), () => AdminCommands.MeasureBodyScale(_playerId));
            Wire(ButtonOf(calibrateButton), PressCalibrate);

            if (nameInput != null)
            {
                // Enter = apply: the operator should not have to reach for the mouse mid-edit.
                nameInput.onSubmit.RemoveAllListeners();
                nameInput.onSubmit.AddListener(_ => ApplyNameEdit());
            }

            SetNameEditActive(false);
            RefreshKickButton();
            RefreshResetButton();
            RefreshCalibrateButton();
        }

        private static Button ButtonOf(UiButtonStyle style)
        {
            return style != null ? style.TargetButton : null;
        }

        private static void Wire(Button button, UnityAction action)
        {
            if (button == null)
            {
                return;
            }

            button.onClick.RemoveAllListeners();
            button.onClick.AddListener(action);
        }

        private static void SetCellActive(Component cell, bool active)
        {
            if (cell != null && cell.gameObject.activeSelf != active)
            {
                cell.gameObject.SetActive(active);
            }
        }

        /// <summary>Binds the row to a player (called on every refresh).</summary>
        public void Bind(AdminPlayerView view, bool selected)
        {
            if (view == null)
            {
                return;
            }

            // ⚠️ Open modes are CLOSED when the row rebinds to another player: a kept edit mode
            // would send one player's typed name to another, and a pending load would show the
            // previous player's result here.
            if (_playerId != view.playerId)
            {
                SetNameEditActive(false);
                _kickArmedAt = -1f;
                _resetHold?.Cancel();
                _purgedAt = -1f;
                SetLoadState(LoadState.Idle);
            }

            _playerId = view.playerId;
            _calibrated = view.calibrated;
            _hasLeft = view.HasLeft;
            _floorOffset = view.floorOffset;

            // Graded dimming: connected 1.0, expected back 0.7, left 0.5 — "may return" and "gone"
            // are two different operator decisions.
            float alpha = view.IsConnected ? 1f : view.IsReconnecting ? ReconnectingAlpha : LeftAlpha;

            ApplyRowSurface(view, selected, alpha);
            ApplyIdentity(view, alpha);
            ApplyStateChip(view, alpha);
            ApplyCounters(view, alpha);
            ApplyTelemetry(view, alpha);
            ApplyViolations(view, alpha);

            // A left row has no command target (§10.2): the player is out, the row only carries
            // match stats. A dead button would feel like "sent but nothing happened".
            SetInteractable(kickButton, !view.HasLeft);
            SetInteractable(renameButton, !view.HasLeft);
            // ⚠️ Purging needs the headset ONLINE: the server only forwards the command to a live
            // connection, so on a left row it would look sent and delete nothing.
            SetInteractable(resetButton, !view.HasLeft);

            RefreshMeasureButton(view);
            RefreshKickButton();
            RefreshResetButton();
            RefreshCalibrateButton();
        }

        /// <summary>Expires the confirm window, load timeout and result hold (panel calls every
        /// frame).</summary>
        public void Tick()
        {
            if (_kickArmedAt >= 0f && Time.unscaledTime - _kickArmedAt > ConfirmSeconds)
            {
                _kickArmedAt = -1f;
                RefreshKickButton();
            }

            if (_resetHold != null && (_resetHold.IsPressed || _resetHoldPainted))
            {
                RefreshResetButton();
            }

            if (_purgedAt >= 0f)
            {
                // ⚠️ The window starts when the FINGER LIFTS — see AdminPlayerRow.Tick for why.
                if (_resetHold != null && _resetHold.IsPressed)
                {
                    _purgedAt = Time.unscaledTime;
                }
                else if (Time.unscaledTime - _purgedAt > ResultHoldSeconds)
                {
                    _purgedAt = -1f;
                    RefreshResetButton();
                }
            }

            if (_loadState == LoadState.Loading &&
                Time.unscaledTime - _loadStateAt > LoadTimeoutSeconds)
            {
                // No reply at all is treated as a failure: dropping it silently would read as
                // "the command went through".
                ApplyCalibrationResult(false, TimeoutReason);
                return;
            }

            if ((_loadState == LoadState.Ok || _loadState == LoadState.Failed) &&
                Time.unscaledTime - _loadStateAt > ResultHoldSeconds)
            {
                SetLoadState(LoadState.Idle);
            }
        }

        public void SetVisible(bool visible)
        {
            if (gameObject.activeSelf == visible)
            {
                return;
            }

            if (!visible)
            {
                // ⚠️ Never leave edit mode on a hidden row: after a relayout the same row lands on
                // another player and the typed name would go to them.
                SetNameEditActive(false);

                // ⚠️ Half-armed confirms die with the row too: a hidden row gets no Tick (the panel
                // only ticks visible ones), so an armed window would survive the hide and fire the
                // destructive command on the FIRST click after the row comes back.
                _kickArmedAt = -1f;
                _resetHold?.Cancel();
                _purgedAt = -1f;
                RefreshKickButton();
                RefreshResetButton();
            }

            gameObject.SetActive(visible);
        }

        /// <summary>Places the row at the given top offset inside the list; it spans the list's full
        /// width (the cell x positions ARE the table's column grid).</summary>
        public void Place(float top, float height)
        {
            RectTransform rect = Rect;
            rect.anchorMin = new Vector2(0f, 1f);
            rect.anchorMax = new Vector2(1f, 1f);
            rect.pivot = new Vector2(0.5f, 1f);
            rect.offsetMin = new Vector2(0f, -(top + height));
            rect.offsetMax = new Vector2(0f, -top);
        }

        /// <summary>
        /// Puts the button into "loading". The <b>bulk action</b> (TÜMÜNÜ KALİBRE ET) calls this
        /// BEFORE sending: if the command returned its result immediately, the row would not be in
        /// loading state yet and the result would be swallowed unseen.
        /// </summary>
        public void BeginCalibrationLoad()
        {
            SetLoadState(LoadState.Loading);
        }

        /// <summary>
        /// Result of a reload attempt (§5.3 <c>calibration_result</c> or timeout).
        /// <para>No popup on success — the "TAMAM" state is enough; on failure the reason goes to
        /// the panel's toast, since a narrow button cannot carry more than "HATA".</para>
        /// </summary>
        public void ApplyCalibrationResult(bool ok, string error)
        {
            SetLoadState(ok ? LoadState.Ok : LoadState.Failed);

            if (!ok)
            {
                _onPopup?.Invoke(_playerId,
                    string.IsNullOrEmpty(error) ? "kalibrasyon yüklenemedi" : error);
            }
        }

        // ------------------------------------------------------------------- cells

        private void ApplyRowSurface(AdminPlayerView view, bool selected, float alpha)
        {
            if (rowShape != null)
            {
                // Selection is the ONLY row-level border state here: an uncalibrated row is marked
                // by its state chip and its KALİBRE button, so a third red channel would compete
                // with the selection the operator just made.
                rowShape.Outline(selected ? 1f : 0f, Girdap.Acc);
            }

            if (numberPlate != null)
            {
                string team = view.team;
                Color hi = Girdap.TeamHi(team);
                Color lo = Girdap.TeamLo(team);
                if (!view.alive)
                {
                    hi = Dim(hi, DeadColorScale);
                    lo = Dim(lo, DeadColorScale);
                }

                numberPlate.Fill(Fade(hi, alpha), Fade(lo, alpha), UiGradientMode.Vertical);
            }

            if (numberText != null)
            {
                // 0 = unassigned (admins): the plate stays but carries no number.
                numberText.text = view.number > 0 ? view.number.ToString() : "";
                numberText.color = Fade(Color.white, alpha);
            }
        }

        private void ApplyIdentity(AdminPlayerView view, float alpha)
        {
            if (nameText != null && !_editing)
            {
                // ⚠️ Never touch the name while editing: the roster refreshes several times a
                // second and would silently overwrite what the operator typed.
                // The number is its own cell, so the name cell carries the name alone.
                nameText.text = view.name;
                nameText.color = Fade(view.alive ? Girdap.Text : Girdap.Faint, alpha);
            }

            if (idText != null)
            {
                idText.text = $"#{view.playerId}";
                idText.color = Fade(Girdap.Faint, alpha);
            }
        }

        /// <summary>DURUM cell. ⚠️ An uncalibrated headset OUTRANKS the play state: until it is
        /// fixed the player cannot take part, so "hazır" there would be a lie.</summary>
        private void ApplyStateChip(AdminPlayerView view, float alpha)
        {
            if (stateChip == null)
            {
                return;
            }

            // Uncalibrated is NOT a state here: the KALİBRE button already turns warn for it, and
            // the chip keeps saying what the player is doing (mockup `.trow`).
            stateChip.Set(StateText(view), StateChipKind(view));

            if (stateChip.Label != null)
            {
                stateChip.Label.color = Fade(stateChip.Label.color, alpha);
            }
        }

        private static UiChipKind StateChipKind(AdminPlayerView view)
        {
            if (!view.alive)
            {
                return UiChipKind.Dead;
            }

            // Away rows get the chip's base SURFACE (CSS plain `.chip`), not the surfaceless
            // variant: "yeniden bağlanıyor (12 sn)" is a standing condition, and a bare label in a
            // dimmed row reads as a leftover rather than a state.
            if (!view.IsConnected)
            {
                return UiChipKind.Neutral;
            }

            return view.ready ? UiChipKind.Good : UiChipKind.Plain;
        }

        private void ApplyCounters(AdminPlayerView view, float alpha)
        {
            // No weapon or no opponent → the three cells can only print zeros; they are hidden rather
            // than zeroed so the row does not teach the operator to ignore numbers.
            // ⚠️ Written on every Bind, not only switched off: rows are pooled and survive the match.
            bool combat = !ModeRuntime.HidesCombatStats;
            SetCellActive(killsText, combat);
            SetCellActive(deathsText, combat);
            SetCellActive(kdText, combat);

            Color number = Fade(view.IsConnected ? Girdap.Text : Girdap.Faint, alpha);

            if (killsText != null)
            {
                killsText.text = view.kills.ToString();
                killsText.color = number;
            }

            if (deathsText != null)
            {
                deathsText.text = view.deaths.ToString();
                deathsText.color = number;
            }

            if (kdText != null)
            {
                // The ratio is undefined without deaths; printing the kill count in the same format
                // gives a readable value instead of a division by zero.
                kdText.text = view.deaths > 0
                    ? (view.kills / (float)view.deaths).ToString("0.00")
                    : view.kills.ToString("0.00");
                kdText.color = number;
            }

            if (scoreText != null)
            {
                scoreText.text = view.score.ToString();
                scoreText.color = number;
            }
        }

        private void ApplyTelemetry(AdminPlayerView view, float alpha)
        {
            ApplyBattery(view, alpha);
            ApplyController(ctrlLeftBar, view.ctrlL, alpha);
            ApplyController(ctrlRightBar, view.ctrlR, alpha);

            if (bodyIcon != null)
            {
                bodyIcon.color = Fade(BodyColor(view.body), alpha);
            }

            if (floorText != null)
            {
                // Ground floor is the norm, so it is NOT written out: a "0. kat" on every row of
                // every single-floor arena would be noise the operator learns to skip.
                floorText.text = view.floor > 0 ? $"{view.floor}. kat" : EmptyCell;
                floorText.color = Fade(Girdap.Muted, alpha);
            }

            if (pingText != null)
            {
                // §6.7: -1 = no measurement. The dash must not read as "0 ms ping".
                pingText.text = view.rttMs < 0 ? EmptyCell : $"{view.rttMs} ms";
                pingText.color = Fade(Girdap.Muted, alpha);
            }
        }

        private void ApplyBattery(AdminPlayerView view, float alpha)
        {
            bool known = view.battery >= 0f;
            float level = Mathf.Clamp01(view.battery);

            // Unknown stays uncoloured: alarming on a value nobody reported sends the operator
            // running for nothing.
            Color color = !known ? Girdap.Muted
                : level < BatteryCritical ? Girdap.Bad
                : level < BatteryLow ? Girdap.Warn
                : Girdap.Muted;

            if (batteryText != null)
            {
                batteryText.text = known ? $"%{Mathf.RoundToInt(level * 100f)}" : EmptyCell;
                batteryText.color = Fade(color, alpha);
            }

            if (batteryIcon != null)
            {
                batteryIcon.color = Fade(color, alpha);
            }
        }

        /// <summary>
        /// One controller hand as a coloured bar.
        /// <para>⚠️ No percentage possible: controller charge is unreadable under OpenXR on Quest
        /// (§5.1). The actionable fact is "did this hand drop".</para>
        /// </summary>
        private static void ApplyController(UiShape bar, int state, float alpha)
        {
            if (bar == null)
            {
                return;
            }

            Color color;
            switch (state)
            {
                case ArenaProtocol.CONTROLLER_OK:
                    color = Girdap.Muted;
                    break;
                case ArenaProtocol.CONTROLLER_UNTRACKED:
                    color = Girdap.Warn;
                    break;
                case ArenaProtocol.CONTROLLER_LOST:
                    color = Girdap.Bad;
                    break;
                default:
                    color = CtrlUnknown;
                    break;
            }

            bar.Fill(Fade(color, alpha));
        }

        /// <summary>
        /// Body tracking colour.
        /// <para>⚠️ The fault has NO local trace: the player's own screen looks normal, the T-pose
        /// shows only on other screens (§5.1). This cell is the operator's only readout.</para>
        /// </summary>
        private static Color BodyColor(int state)
        {
            switch (state)
            {
                case ArenaProtocol.BODY_OK:
                    return Girdap.Muted;
                case ArenaProtocol.BODY_FALLBACK:
                    return Girdap.Warn;
                case ArenaProtocol.BODY_NO_PERMISSION:
                    return Girdap.Bad;
                default:
                    return CtrlUnknown;
            }
        }

        /// <summary>
        /// Violation ledger cell: one chip per kind, then the last calibration failure.
        /// <para>⚠️ <b>No blinking, no "ongoing" mark</b> — this is the ledger; the live channel is
        /// the HUD strip and the card border.</para>
        /// <para>⚠️ The last reload failure reason STAYS here (§10.6): the toast closes itself after
        /// a few seconds and without a trace the operator is left with "something happened, but
        /// what". The field is held by the SERVER, so a later-joining operator sees the same reason;
        /// a successful calibration clears it, so the row heals itself.</para>
        /// </summary>
        private void ApplyViolations(AdminPlayerView view, float alpha)
        {
            bool obstacle = view.obstacleCount > 0;
            bool outOfBounds = view.outOfBoundsCount > 0;
            bool error = !string.IsNullOrEmpty(view.calibrationError);

            SetChip(obstacleChip, obstacle,
                $"{AdminViolations.Label(AdminViolationKind.Obstacle)} {view.obstacleCount}",
                UiChipKind.Bad, alpha);
            SetChip(outOfBoundsChip, outOfBounds,
                $"{AdminViolations.Label(AdminViolationKind.OutOfBounds)} {view.outOfBoundsCount}",
                UiChipKind.Warn, alpha);
            SetChip(calibrationErrorChip, error, view.calibrationError, UiChipKind.Bad, alpha);

            SetCellActive(violationEmpty, !obstacle && !outOfBounds && !error);
            if (violationEmpty != null)
            {
                violationEmpty.color = Fade(Girdap.Muted, alpha);
            }

            LayoutViolationChips();
        }

        private static void SetChip(UiChip chip, bool visible, string text, UiChipKind kind,
            float alpha)
        {
            if (chip == null)
            {
                return;
            }

            SetCellActive(chip, visible);
            if (!visible)
            {
                return;
            }

            chip.Set(text, kind);
            if (chip.Label != null)
            {
                chip.Label.color = Fade(chip.Label.color, alpha);
            }
        }

        /// <summary>Flows the visible ledger chips left to right. ⚠️ Widths come from
        /// <see cref="UiChip.Set"/>, so the order has to be re-measured here rather than authored —
        /// no Layout Group in this kit.</summary>
        private void LayoutViolationChips()
        {
            float x = 0f;
            x = PlaceChip(obstacleChip, x);
            x = PlaceChip(outOfBoundsChip, x);
            PlaceChip(calibrationErrorChip, x);
        }

        private static float PlaceChip(UiChip chip, float x)
        {
            if (chip == null || !chip.gameObject.activeSelf || chip.Root == null)
            {
                return x;
            }

            RectTransform rect = chip.Root;
            rect.anchoredPosition = new Vector2(x, rect.anchoredPosition.y);
            return x + rect.sizeDelta.x + 4f; // CSS .viol gap
        }

        private static Color Fade(Color c, float alpha)
        {
            c.a *= alpha;
            return c;
        }

        private static Color Dim(Color c, float scale)
        {
            return new Color(c.r * scale, c.g * scale, c.b * scale, c.a);
        }

