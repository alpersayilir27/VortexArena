    /// <summary>
    /// Single player row of the stats table: number plate, name + <c>#id</c>, state chip, the
    /// K/D/KD/score cells, telemetry cells (battery · controllers · body · floor · ping), the
    /// violation ledger and the action strip (KALİBRE · ÖLÇ · rename · SIFIRLA · AT).
    /// <para>
    /// <b>Why a sibling of <see cref="AdminPlayerRow"/> but a separate class:</b> the side card is
    /// narrow and belongs to scene control (POV/team/identity); this row is wide, table-like
    /// and belongs to the operator's <i>record keeping</i> screen. Merging them means a "which
    /// screen am I on" branch in every <c>Bind</c>, where a fix for one screen silently breaks the
    /// other.
    /// </para>
    /// <para>
    /// <b>Look comes from the prefab</b> (<c>Assets/_Shared/App/Resources/UI/</c>, generated by
    /// <c>GirdapUiBuilder</c>); this class is behaviour only. Unbound prefab fields silently draw
    /// nothing.
    /// </para>
    /// <para>
    /// ⚠️ <b>ONE row prefab, one table.</b> There is no narrow/icon variant: the panel draws every
    /// player in a single full-width table with a group row per team. Do not fork a second prefab —
    /// the cell x positions are the table's column grid and a second copy drifts away from it.
    /// </para>
    /// <para>
    /// ⚠️ <b>HP is absent by DESIGN</b> — it lives on the side panel card as a bar. Violations
    /// appear here as a <b>ledger</b> (count per kind) and deliberately do not blink: the live
    /// channel is the HUD strip and the card border.
    /// </para>
    /// <para>
    /// ⚠️ <b>SIFIRLA is ONE button carrying BOTH reset modes</b> (<see cref="HoldButton"/>): a tap
    /// voids the current alignment and keeps the headset's saved anchor, a 1 s hold wipes that
    /// anchor too — afterwards KALİBRE fails and the player must redo the A/B sequence by hand.
    /// Severity comes from press DURATION, never from picking the right neighbour: two separate
    /// buttons made the operator choose a severity before knowing they needed one, and put the
    /// destructive one a mis-click away. The side card (<see cref="AdminPlayerRow"/>) carries no
    /// calibration button; this row is the only place.
    /// </para>
    /// <para>
    /// ⚠️ <b>KALİBRE is the OPPOSITE action and stays its own button:</b> it <i>reloads</i>
    /// alignment from the saved anchor and destroys nothing. The two sit at opposite ends of the
    /// button strip so a mis-aimed click cannot land on the other.
    /// </para>
    /// </summary>
    public class AdminStatsRow : MonoBehaviour
