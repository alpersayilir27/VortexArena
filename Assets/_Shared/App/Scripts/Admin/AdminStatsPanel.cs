    /// <summary>
    /// Stats panel (opened by the chip between the scores or the <c>I</c> key).
    /// <para><b>Why row based:</b> the panel is not a read-only table but the screen where the
    /// operator does <i>record keeping</i> (fixing names, body measurement, calibration reload).
    /// Each player is a row (<see cref="AdminStatsRow"/>): alignment comes from the column grid,
    /// actions sit on the row and the list scrolls — <b>no cap</b>, everyone is drawn.</para>
    /// <para><b>ONE table for every player.</b> In a team mode a group row per team breaks it up
    /// (<see cref="RefreshRows"/>); a team-less mode draws the same table ranked by score, with no
    /// group rows. ⚠️ No two-column split any more: two half-width copies of the row meant two
    /// column grids that drifted apart, and the narrow copy could not carry the row's cells.</para>
    /// <para>⚠️ <b>Team-less players stay visible</b> in a team mode — see
    /// <see cref="BuildRedSection"/>; they are the whole roster during Lobby.</para>
    /// <para><b>No invented metrics:</b> only data actually on the wire (K/D/score from §5.3
    /// <c>lobby_state</c>; battery/controllers from <c>status</c>; ping = client-measured RTT,
    /// §6.7 <c>net_stats</c>). ⚠️ <b>Damage and accuracy are not in the protocol, so not here
    /// either.</b> Jitter and packet loss are measured but not shown: ping is the only number the
    /// operator can act on.</para>
    /// <para>⚠️ <b>HP is deliberately absent from the row</b> — reasoning in the
    /// <see cref="AdminStatsRow"/> class doc; do not "restore" it.</para>
    /// <para>⚠️ <b>There is no BULK reset button.</b> Resetting alignment is a per-player decision
    /// made on the row (SIFIRLA, tap/hold); the footer only carries the three harmless bulk jobs
    /// (body tracking restart, measure everyone, reload everyone's calibration).</para>
    /// <para><b>Look comes from the prefab</b>
    /// (<c>_Shared/App/Resources/UI/AdminStatsPanel.prefab</c>, generated by
    /// <c>GirdapUiBuilder</c>); this class only writes data and places rows.</para>
    /// </summary>
    public class AdminStatsPanel : MonoBehaviour
